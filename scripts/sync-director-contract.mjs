import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const sourceURL = new URL("../services/director-gateway/src/contract.js", import.meta.url);
const targetURL = new URL("../packages/performance/src/directorContract.generated.ts", import.meta.url);
const source = await readFile(sourceURL, "utf8");
const browserSource = source.replace(
  'import { performanceDirectionSkill, performanceDirectionSystemPrompt } from "./skill.js";',
  'import { performanceDirectionSkill, performanceDirectionSystemPrompt } from "./directorBrowserSkill";',
);

if (browserSource === source) {
  throw new Error(`Director contract import was not found in ${fileURLToPath(sourceURL)}`);
}

const generated = [
  "// @ts-nocheck",
  "// Generated by scripts/sync-director-contract.mjs from the server contract.",
  "// Do not edit this file directly.",
  browserSource,
].join("\n");

await writeFile(targetURL, generated, "utf8");
