import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const schemasURL = new URL("../packages/contracts/schemas/", import.meta.url);
const outputURL = new URL("../packages/contracts/src/generated/validators.mjs", import.meta.url);
const readSchema = (name) => JSON.parse(readFileSync(new URL(name, schemasURL), "utf8"));

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  code: { esm: true, source: true },
});

ajv.addSchema(readSchema("recording-identity-v0.schema.json"), "recordingIdentityV0");
ajv.addSchema(readSchema("lyric-document-v0.schema.json"), "lyricDocumentV0");
ajv.addSchema(readSchema("director-recipe-v0.schema.json"), "directorRecipeV0");
ajv.addSchema(readSchema("lyricstage-manifest-v0.schema.json"), "lyricStageManifestV0");

const standaloneSource = standaloneCode(ajv, {
  validateRecordingIdentity: "recordingIdentityV0",
  validateLyricDocumentShape: "lyricDocumentV0",
  validateDirectorRecipeShape: "directorRecipeV0",
  validateManifestShape: "lyricStageManifestV0",
});
const source = standaloneSource.replace(
  'const func1 = require("ajv/dist/runtime/ucs2length").default;',
  `const func1 = (value) => {
  let length = value.length;
  for (let index = 0; index < value.length; index += 1) {
    const code = value.charCodeAt(index);
    if (code >= 0xd800 && code <= 0xdbff && index + 1 < value.length) {
      const next = value.charCodeAt(index + 1);
      if (next >= 0xdc00 && next <= 0xdfff) {
        index += 1;
        length -= 1;
      }
    }
  }
  return length;
};`,
);

if (source.includes("require(") || source.includes("new Function")) {
  throw new Error("Generated validators are not extension-CSP-safe");
}

mkdirSync(fileURLToPath(new URL(".", outputURL)), { recursive: true });
writeFileSync(
  outputURL,
  `/* Generated by scripts/generate-contract-validators.mjs. Do not edit. */\n${source}`,
  "utf8",
);
